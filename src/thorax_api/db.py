"""Shared database access: SQLite (a file path) or PostgreSQL (a postgresql:// URL, e.g. AWS RDS).

The stores write one portable SQL dialect with sqlite3's `?` placeholders. For PostgreSQL this module
translates the few remaining differences, so the stores do not change:
- `?` placeholders become `%s`;
- `BEGIN IMMEDIATE` (SQLite's single-writer lock) becomes one transaction-scoped advisory lock;
- in table definitions, `id INTEGER PRIMARY KEY` becomes an identity column and `REAL` double precision
  (PostgreSQL's REAL is 4-byte and would round millisecond timestamps);
- after inserts with explicit ids, the identity sequence moves past the largest id.
"""

from __future__ import annotations

import re
import sqlite3
from collections.abc import Iterator
from contextlib import contextmanager
from datetime import datetime, timezone
from pathlib import Path

try:
    import psycopg
    IntegrityError: tuple = (sqlite3.IntegrityError, psycopg.IntegrityError)
except ImportError:  # SQLite-only installs
    psycopg = None
    IntegrityError = (sqlite3.IntegrityError,)

WRITE_LOCK = 7311  # any constant: every writer takes the same advisory lock, like SQLite's single writer
_EXPLICIT_ID = re.compile(r"^\s*INSERT INTO (\w+) \(id,", re.IGNORECASE)
_IDENTITY = re.compile(r"(?<!\w)id INTEGER PRIMARY KEY")


def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds").replace("+00:00", "Z")


def is_postgres(target: str | Path) -> bool:
    return str(target).startswith(("postgresql://", "postgres://"))


class Row(tuple):
    """Index and column-name access, like sqlite3.Row (so `dict(row)` and `row["id"]` keep working)."""

    def __getitem__(self, key):
        return tuple.__getitem__(self, self._names.index(key) if isinstance(key, str) else key)

    def keys(self) -> list[str]:
        return list(self._names)


def _rows(cursor):
    names = tuple(column.name for column in cursor.description or ())

    def make(values):
        row = Row(values)
        row._names = names
        return row
    return make


def _postgres_sql(sql: str) -> str:
    if sql.strip().upper() == "BEGIN IMMEDIATE":
        return f"SELECT pg_advisory_xact_lock({WRITE_LOCK})"
    if sql.lstrip().upper().startswith("CREATE TABLE"):
        sql = _IDENTITY.sub("id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql).replace(" REAL", " DOUBLE PRECISION")
    return sql.replace("%", "%%").replace("?", "%s")


class _PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    @property
    def in_transaction(self) -> bool:  # same meaning as sqlite3.Connection.in_transaction
        return self._connection.info.transaction_status != psycopg.pq.TransactionStatus.IDLE

    def _sync_identity(self, sql: str) -> None:
        if match := _EXPLICIT_ID.match(sql):
            table = match.group(1)
            self._connection.execute(f"SELECT setval(pg_get_serial_sequence('{table}', 'id'), (SELECT COALESCE(MAX(id), 0) + 1 FROM {table}), false)")

    def execute(self, sql: str, params=()):
        if sql.strip().upper().startswith("PRAGMA FOREIGN_KEYS"):
            return self._connection.execute("SELECT 1")  # PostgreSQL always enforces foreign keys
        cursor = self._connection.execute(_postgres_sql(sql), tuple(params))
        self._sync_identity(sql)
        return cursor

    def executemany(self, sql: str, rows) -> None:
        rows = list(rows)
        if rows:
            with self._connection.cursor() as cursor:
                cursor.executemany(_postgres_sql(sql), rows)
            self._sync_identity(sql)


@contextmanager
def connect(target: str | Path) -> Iterator:
    """One transaction: commits on success, rolls back on error, always closes."""
    if is_postgres(target):
        if psycopg is None:
            raise RuntimeError("A postgresql:// database needs psycopg (requirements/api.txt).")
        # ponytail: one connection per operation; fine for one API worker in the same VPC as RDS. Add a pool for more load.
        with psycopg.connect(str(target), row_factory=_rows) as connection:
            yield _PostgresConnection(connection)
        return
    # sqlite3's own context manager only commits; close explicitly so handles do not leak.
    db = sqlite3.connect(str(target))
    db.row_factory = sqlite3.Row
    db.execute("PRAGMA foreign_keys = ON")
    try:
        with db:
            yield db
    finally:
        db.close()


def columns(db, table: str, target: str | Path) -> set[str]:
    """Column names of a table, to add columns that later releases introduced."""
    if is_postgres(target):
        return {row[0] for row in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = ?", (table,))}
    return {row[1] for row in db.execute(f"PRAGMA table_info({table})")}
