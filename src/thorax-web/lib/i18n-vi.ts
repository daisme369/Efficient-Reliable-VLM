/** Vietnamese for one UI string, keeping its surrounding whitespace; null when it is not UI text we know. */
export function translate(text: string): string | null {
  const key = text.replace(/\s+/g, ' ').trim();
  if (!key) return null;
  const exact = VI[key];
  if (exact !== undefined) return text.replace(key, exact);
  for (const [pattern, render] of VI_PATTERNS) {
    const match = pattern.exec(key);
    if (match) return text.replace(key, render(...match.slice(1)));
  }
  return null;
}
